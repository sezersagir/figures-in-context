"""Judge calibration: do the judges find deliberately planted errors without flagging clean answers?

    python -m figures_in_context calibration [--test]     (or in the web app under "Calibration")

The answers are in calibration/answers.json (generated by calibration/_source/generate.py),
each with `expected` = the planted error types. The judges see exactly what they see in a real run.
Result: calibration_runs/<name>/calibration.md and .html, plus result.json for the web app.

Scoring per judge, only for the error types it is responsible for:
- Hit: answer with a planted error of its type, the judge flags and names the type.
- False alarm: clean answer, the judge flags anyway.
Answers with errors of other types don't count for it (knock-on errors may be noticed).
Passed means: every planted error found, no false alarm, no broken verdict.
"""

import json
from datetime import datetime

from . import check, data, judges
from .report import rate, to_html

ANSWERS = data.BASE / "calibration" / "answers.json"
RUNS_DIR = data.BASE / "calibration_runs"
MODEL = "calibration"
NAMES = {"numbers": "Numbers judge", "calculation": "Calculation judge", "plausibility": "Plausibility judge"}


class CalibrationError(Exception):
    pass


def load_answers():
    answers = data.load_json(ANSWERS)
    for no, a in enumerate(answers, 1):
        a["model"], a["repetition"] = MODEL, no
    return answers


def new(test=False):
    config = data.load_config()
    judges_config = {j: {"provider": "test", "model": f"judge-{j}"} for j in config["judges"]} if test \
        else config["judges"]
    name = datetime.now().strftime("%Y-%m-%d_%H%M%S") + ("_test" if test else "")
    run_dir = RUNS_DIR / name
    run_dir.mkdir(parents=True)
    answers = load_answers()
    (run_dir / "run.json").write_text(json.dumps({
        "test_cases": config["test_cases"],
        "judges": judges_config,
        "parallel": config.get("parallel", 4),
        "test": test,
        "record": {
            "prompt_hashes": {f"judge_{j}": data.text_hash(data.load_prompt(f"judge_{j}")) for j in judges_config},
            "answers_hash": data.text_hash(json.dumps(answers, sort_keys=True, ensure_ascii=False)),
        },
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    return run_dir


def load(name):
    run_dir = RUNS_DIR / name
    if "/" in name or "\\" in name or ".." in name or not (run_dir / "run.json").exists():
        raise CalibrationError(f"Calibration {name} not found.")
    return run_dir, data.load_json(run_dir / "run.json")


def all_calibrations():
    if not RUNS_DIR.exists():
        return []
    return sorted((p.name for p in RUNS_DIR.iterdir() if (p / "run.json").exists()), reverse=True)


def start(run_dir, config):
    """Writes the calibration answers, runs the Python check and the judges, and scores the result."""
    answers = load_answers()
    cases = data.load_test_cases(config["test_cases"])
    unknown = sorted({a["case_id"] for a in answers} - set(cases))
    if unknown:
        raise CalibrationError(f"Test cases missing: {', '.join(unknown)}")
    target = run_dir / "answers.jsonl"
    if not target.exists():
        for a in answers:
            data.append(target, {k: a[k] for k in ("case_id", "model", "repetition", "answer_text")})
    check.run(run_dir, cases)
    ok = judges.run(run_dir, config, cases)
    if not ok:
        data.log(run_dir, "warning", "Not all judge requests succeeded. Just start again.")
        return False
    evaluate(run_dir, config)
    return True


def score(answers, verdicts, judge_names):
    """→ {judge: {hits, expected, false_alarms, clean, broken, wrong_type, missed: [...], alarms: [...]}}"""
    by_key = {(v["repetition"], v["judge"]): v for v in verdicts}
    result = {}
    for judge in judge_names:
        responsible = set(judges.ALLOWED[judge])
        e = {"hits": 0, "expected": 0, "false_alarms": 0, "clean": 0, "broken": 0, "wrong_type": 0,
             "missed": [], "alarms": []}
        for a in answers:
            v = by_key.get((a["repetition"], judge))
            if v is None:
                continue
            if v.get("judge_error"):
                e["broken"] += 1
            planted = set(a["expected"]) & responsible
            if planted:
                e["expected"] += 1
                if v["flag"] and planted & set(v["error_types"]):
                    e["hits"] += 1
                else:
                    if v["flag"]:
                        e["wrong_type"] += 1
                    e["missed"].append({**_short(a), "finding": v.get("finding", "")})
            elif not a["expected"]:
                e["clean"] += 1
                if v["flag"]:
                    e["false_alarms"] += 1
                    e["alarms"].append({**_short(a), "finding": v.get("finding", ""), "types": v["error_types"]})
        e["passed"] = e["expected"] > 0 and e["hits"] == e["expected"] and e["false_alarms"] == 0 and e["broken"] == 0
        result[judge] = e
    return result


def _short(a):
    return {"cal_id": a["cal_id"], "case_id": a["case_id"], "description": a["description"]}


def evaluate(run_dir, config):
    answers = load_answers()
    verdicts = data.read_jsonl(run_dir / "verdicts.jsonl")
    result = score(answers, verdicts, list(config["judges"]))

    md = [f"# Judge calibration {run_dir.name}", ""]
    if config.get("test"):
        md += ["**Test run with test models: these numbers say nothing about real judges.**", ""]
    md += [f"{len(answers)} answers, {sum(1 for a in answers if not a['expected'])} of them clean. "
           "Goal: find every planted error and flag no clean answer.", "",
           "| Judge | Model | Found | False alarms | Broken verdicts | Result |", "|---|---|---|---|---|---|"]
    for judge, e in result.items():
        target = config["judges"][judge]
        md.append(f"| {NAMES.get(judge, judge)} | {target['provider']}:{target['model']} | {rate(e['hits'], e['expected'])} | "
                  f"{rate(e['false_alarms'], e['clean'])} | {e['broken']} | "
                  f"{'**passed**' if e['passed'] else '**needs work**'} |")
    md += ["", "With this few answers the confidence intervals are wide. The calibration mainly shows "
           "which errors a judge misses, and for that the individual cases below are worth a look.", ""]
    for judge, e in result.items():
        if not (e["missed"] or e["alarms"]):
            continue
        md += [f"## {NAMES.get(judge, judge)}", ""]
        for m in e["missed"]:
            md.append(f"- **Missed** {m['cal_id']} ({m['case_id']}, {m['description']}): {m['finding']}")
        for m in e["alarms"]:
            md.append(f"- **False alarm** {m['cal_id']} ({m['case_id']}): {', '.join(m['types']) or 'flag'}: {m['finding']}")
        md.append("")
    md += ["## What to do when a judge \"needs work\"", "",
           "- Read the judge's finding on the missed cases: did it not see the error, or file it under the wrong type?",
           "- Adjust the prompt in the prompts folder (judge_numbers.md, judge_calculation.md, judge_plausibility.md) or pick another model in the settings.",
           "- Then start a new calibration. A real run only fully counts once all three have passed.", ""]
    text = "\n".join(md)
    (run_dir / "calibration.md").write_text(text, encoding="utf-8")
    (run_dir / "calibration.html").write_text(to_html(text, f"Calibration {run_dir.name}"), encoding="utf-8")
    (run_dir / "result.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
    data.log(run_dir, "info", "Calibration: " + ", ".join(
        f"{NAMES.get(j, j)} {e['hits']}/{e['expected']} found, {e['false_alarms']} false alarms"
        for j, e in result.items()))
    return result


def status(run_dir):
    """For the overview in the web app."""
    config = data.load_json(run_dir / "run.json")
    n = len(data.load_json(ANSWERS))
    result_file = run_dir / "result.json"
    return {
        "test": config.get("test", False),
        "judges": {j: f"{t['provider']}:{t['model']}" for j, t in config["judges"].items()},
        "verdicts": len(data.read_jsonl(run_dir / "verdicts.jsonl")),
        "verdicts_expected": n * len(config["judges"]),
        "result": data.load_json(result_file) if result_file.exists() else None,
    }
